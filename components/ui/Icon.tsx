interface IconProps extends Omit<LucideProps, "ref"> {
  name: string;
}

// Size with Tailwind, e.g. className="size-4" (Material text-xs/sm/base/lg/xl
// = size-3 / size-3.5 / size-4 / size-4.5 / size-5).
// For a filled icon (Material "star"), add fill-current to className.
export function Icon({ name, className = "", ...props }: IconProps) {
  const LucideIcon = ICONS[name];

  if (!LucideIcon) {
    if (process.env.NODE_ENV !== "production") {
      console.warn(`[Icon] No lucide mapping for "${name}". Add it to ICONS in Icon.tsx.`);
    }
    return <CircleHelp aria-hidden className={`shrink-0 ${className}`} {...props} />;
  }

  return <LucideIcon aria-hidden className={`shrink-0 ${className}`} {...props} />;
}
